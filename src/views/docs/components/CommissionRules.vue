        <h2>1. 两个部门如何分配</h2>
        <p>同一笔业务先形成一个提成池，再分成客户拓展、招聘交付两部分。客户拓展贡献涵盖开发与维护；招聘交付贡献涵盖寻访、推荐、推进及入职服务。多人协作可添加多名人员，各部门内分配分别合计 100%，避免按两个部门各算一份完整提成。</p>
        <p>每份规则明确：业务类型、生效日期、总提成率、拓展部门比例、交付入职首期释放比例。交付部门比例为 100% 减拓展比例；保证期尾款比例为 100% 减首期比例。销售满足回款条件后释放其对应提成，不受交付首期比例影响；服务验收模式释放已分摊的交付预算。零预算部门无需维护人员。</p>
        <h2>2. 首单、续单与归属</h2>
        <p>新客首单和老客续单可配置不同规则。财务与业务主管核对客户历史后明确选择业务类型；同一客户的首单合同下可有多个招聘成果，但不能将另一份合同也确认为首单。历史客户首次录入系统不代表新客。续单无需虚构一份历史首单。</p>
        <p>生效合同先绑定提成规则并确认拓展销售归属，同时选择交付按入职或服务验收结算。系统建议的当前客户负责人仅供核对，不自动认定原始开发人。开发人与维护人不同，应明确各人的部门内份额并填写依据；交付人员在各招聘成果或验收记录内独立维护。</p>
        <p>确认后冻结人员、部门名称、规则版本与比例。负责人转交、员工调岗、规则停用都不覆盖已确认记录。招聘交付须实际入职后确认归属；服务交付须登记收费条款、验收日期及凭据。已有原方式招聘归属的合同继续沿用原核算，不再叠加合同销售提成。已有分摊或核算的记录通过新差额处理，不修改已批准历史。</p>
        <h2>3. 什么金额可以计提</h2>
        <p>合同额只用于预计提成。核算只使用合同实际到账流水，不使用应收、开票金额或审批中的回款。销售自动按合同净回款核算，无需等候招聘或手工分摊；交付需把到账分摊至相同合同、相同收费条款下已确认的招聘成果或验收记录。一笔到账可分配给多个成果，分摊合计不能超过原到账。</p>
        <p>当前口径按实际到账金额计提，到账中包含税额时也包含在基数中，不自动扣除税费或成本。非合同手工应收暂不纳入招聘提成。若公司采用不含税收入或毛利口径，应另行明确口径后扩展，不能仅调整一个比例冒充扣税或扣成本。</p>
        <pre>合同净回款 = 原到账金额 − 关联原到账的已确认退款及冲销
合同提成池 = 合同净回款 × 总提成率
销售提成预算 = 合同提成池 × 拓展比例
交付提成预算 = 合同提成池 − 销售提成预算
各交付成果预算按其分摊净回款分配；未分摊部分暂不释放
个人累计提成 = 部门提成 × 部门内个人比例
本次核算差额 = 累计满足释放条件的个人提成 − 以前核算及占用金额</pre>
        <p>金额保留两位小数，按部门和个人顺序分配尾差，确保个人合计等于部门金额，两部门合计等于提成池。</p>
