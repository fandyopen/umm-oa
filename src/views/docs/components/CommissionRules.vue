        <h2>1. 两个部门如何分配</h2>
        <p>同一笔业务先形成一个提成池，再分成客户拓展、招聘交付两部分。客户拓展贡献涵盖开发与维护；招聘交付贡献涵盖寻访、推荐、推进及入职服务。多人协作可添加多名人员，各部门内分配分别合计 100%，避免按两个部门各算一份完整提成。</p>
        <p>每份规则明确：业务类型、生效日期、总提成率、拓展部门比例、首期释放比例。交付部门比例为 100% 减拓展比例；保证期尾款比例为 100% 减首期比例。零预算部门无需维护人员。</p>
        <h2>2. 首单、续单与归属</h2>
        <p>新客首单和老客续单可配置不同规则。财务与业务主管核对客户历史后明确选择业务类型；同一客户的首单合同下可有多个招聘成果，但不能将另一份合同也确认为首单。历史客户首次录入系统不代表新客。续单无需虚构一份历史首单。</p>
        <p>每条招聘成果单独维护人员归属。系统建议的当前客户负责人和招聘顾问仅供核对，不自动认定原始开发人。开发人与维护人不同，应作为客户拓展贡献的协作人员明确分配比例，并填写归属依据；顾问协作同理。</p>
        <p>实际入职后确认归属，冻结人员、部门名称、规则版本与比例。负责人转交、员工调岗、规则停用都不覆盖已确认记录。已有分摊或核算的归属不能直接撤销，调整通过原回款重新分摊及新差额核算留痕处理；需要改变人员时，先由业务主管核实应采用的业务更正方案，不能修改已批准历史。</p>
        <h2>3. 什么金额可以计提</h2>
        <p>只使用合同的实际到账流水，不使用合同总额、应收、开票金额或审批中的回款。先把到账分摊至相同合同、相同收费条款下已确认的招聘成果；一笔到账可分配给多个成果，分摊合计不能超过原到账。</p>
        <p>当前口径按实际到账金额计提，到账中包含税额时也包含在基数中，不自动扣除税费或成本。非合同手工应收暂不纳入招聘提成。若公司采用不含税收入或毛利口径，应另行明确口径后扩展，不能仅调整一个比例冒充扣税或扣成本。</p>
        <pre>分摊净回款 = 分摊金额 ×（原到账金额 − 原到账已确认退款及冲销）÷ 原到账金额
提成池 = 分摊净回款 × 总提成率
部门提成 = 提成池 × 部门比例
个人累计提成 = 部门提成 × 部门内个人比例
本次核算差额 = 累计满足释放条件的个人提成 − 以前核算及占用金额</pre>
        <p>金额保留两位小数，按部门和个人顺序分配尾差，确保个人合计等于部门金额，两部门合计等于提成池。</p>
        <h2>4. 入职、保证期与异常</h2>
        <a-table :columns="conditionColumns" :data-source="conditions" row-key="state" :pagination="false" size="small" />
        <p>保证期自然到期不会自动释放尾款，必须在招聘流程登记保证期完成，且保证期结束日不晚于核算截止日。只发生成交、Offer 或预计入职不能代替实际入职。</p>
        <h2>5. 退款、冲销、离职与免费替换</h2>
        <p>实际退款或到账冲销须在财务中关联原到账，并完成确认。系统按原到账比例扣减净回款，已核算部分在下一批产生负数扣回，不改写旧批次。退款申请待批或待付款时不提前视为退款。应收核销不代表现金退款。</p>
        <p>招聘流程登记“退费”只暂缓新增释放；实际资金扣减以财务确认结果为准，避免招聘退费事件与财务退款重复扣款。离职、替换等异常阶段暂缓新增释放，仍处理实际退款导致的扣回。</p>
        <p>免费替换沿用原交付的规则和预算。在同一笔原到账中，将金额从原交付转移至替换交付，分摊总额不变；原人员可能产生扣回，替换人员按新的入职及保证期进度释放。不能给原交付和免费替换各分配一遍完整收入。若替换另行收费，应登记新增真实回款。</p>
